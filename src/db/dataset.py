# ===========================================================================
# REFERENCE TOOL LAYER
# ===========================================================================
# These functions are a reference implementation of the "tools" the agent
# would call (get_ticket, get_tickets_by_customer, get_refund_policy,
# resolve_ticket, update_customer_email, ...). They operate on the in-memory
# lists above and show the validation / not-found / error-shape behavior a
# real tool backend should have -- e.g. returning an explicit {"error": ...}
# instead of raising, so the agent has something concrete to reason about
# and relay to the human support rep it's assisting.
#
# This is a reference / seed implementation, not a framework: swap the
# in-memory lookups for real DB queries when wiring this into production.


_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")


def _parse(ts):
    return datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


def get_customer(customer_id):
    """Look up one customer by id. Returns dict or an explicit not-found error."""
    for c in CUSTOMERS:
        if c["customer_id"] == customer_id:
            return c
    return {"error": "customer_not_found", "customer_id": customer_id}


def find_customer_by_email(email):
    for c in CUSTOMERS:
        if c["email"].lower() == email.lower():
            return c
    return {"error": "customer_not_found", "email": email}


def get_ticket(ticket_id):
    """Look up one ticket by id. Returns dict or an explicit not-found error."""
    for t in TICKETS:
        if t["ticket_id"] == ticket_id:
            return t
    return {"error": "ticket_not_found", "ticket_id": ticket_id}


def get_tickets_by_customer(customer_id, status=None):
    """All tickets for a customer, optionally filtered by status.
    Returns [] (not an error) when the customer exists but has no matching
    tickets -- that's a normal, expected outcome, not a failure.
    """
    if isinstance(get_customer(customer_id), dict) and "error" in get_customer(
        customer_id
    ):
        return {"error": "customer_not_found", "customer_id": customer_id}
    results = [t for t in TICKETS if t["customer_id"] == customer_id]
    if status:
        results = [t for t in results if t["status"] == status]
    return results


def count_tickets_by_status(customer_id):
    """{'open': n, 'resolved': n, 'escalated': n} for one customer (zeros included)."""
    counts = {"open": 0, "resolved": 0, "escalated": 0}
    tickets = get_tickets_by_customer(customer_id)
    if isinstance(tickets, dict):
        return tickets
    for t in tickets:
        counts[t["status"]] += 1
    return counts


def search_tickets(
    category=None, status=None, book_category=None, contains_prompt_injection=None
):
    """Filter across ALL tickets/customers -- for aggregate / cross-customer questions."""
    results = TICKETS
    if category is not None:
        results = [t for t in results if t["category"] == category]
    if status is not None:
        results = [t for t in results if t["status"] == status]
    if book_category is not None:
        results = [t for t in results if t["book_category"] == book_category]
    if contains_prompt_injection is not None:
        results = [
            t
            for t in results
            if t["contains_prompt_injection"] == contains_prompt_injection
        ]
    return results


def get_refund_policy(book_category, format=None):
    """Look up the refund policy for a category (+ optional format).
    If format is omitted for a category that differs by format, returns
    BOTH branches so the caller/agent can ask a clarifying question rather
    than silently guessing physical vs ebook.
    """
    if book_category not in REFUND_POLICY:
        return {
            "error": "unknown_category",
            "book_category": book_category,
            "valid_categories": list(REFUND_POLICY.keys()),
        }
    policy = REFUND_POLICY[book_category]
    if format is None:
        return {
            "book_category": book_category,
            "description": policy["description"],
            "physical": policy["physical"],
            "ebook": policy["ebook"],
            "note": "No format specified -- returning both physical and ebook windows.",
        }
    if format not in ("physical", "ebook"):
        return {"error": "unknown_format", "format": format}
    return {"book_category": book_category, "format": format, **policy[format]}


def refund_window_days_for(customer_id, book_category, format="physical"):
    """Effective refund window in days for THIS customer (applies the Prime
    +7-day bonus on physical windows). Returns None for ebook-by-hours cases
    (technology ebook is a 24-HOUR window, not days) -- check the 'hours' key
    in that case.
    """
    customer = get_customer(customer_id)
    if "error" in customer:
        return customer
    policy = get_refund_policy(book_category, format)
    if "error" in policy:
        return policy
    days = policy.get("refund_window_days")
    if days is None:
        return policy  # e.g. technology/ebook uses refund_window_hours instead
    if format == "physical" and customer["membership_tier"] == "prime":
        days += GENERAL_POLICY["prime_member_bonus_days"]
    return {
        "book_category": book_category,
        "format": format,
        "effective_refund_window_days": days,
        "prime_bonus_applied": format == "physical"
        and customer["membership_tier"] == "prime",
    }


def is_within_refund_window(ticket_id, as_of=None):
    """Convenience check combining a ticket's order_date + category + the
    customer's membership tier into a yes/no + explanation. Does NOT itself
    check condition text (e.g. 'must be unopened') -- that still needs human
    or agent judgment from the policy's 'condition' field.
    """
    ticket = get_ticket(ticket_id)
    if "error" in ticket:
        return ticket
    if not ticket.get("book_category") or not ticket.get("order_date"):
        return {
            "error": "not_applicable",
            "reason": "ticket has no associated book/order",
        }
    as_of_dt = _parse(as_of) if as_of else datetime.now(timezone.utc)
    order_dt = _parse(ticket["order_date"])
    age_days = (as_of_dt - order_dt).days
    window = refund_window_days_for(
        ticket["customer_id"], ticket["book_category"], ticket["format"] or "physical"
    )
    if "error" in window:
        return window
    if "effective_refund_window_days" in window:
        within = age_days <= window["effective_refund_window_days"]
        return {
            "ticket_id": ticket_id,
            "order_age_days": age_days,
            "effective_refund_window_days": window["effective_refund_window_days"],
            "prime_bonus_applied": window["prime_bonus_applied"],
            "within_window": within,
        }
    return (
        window  # hours-based window (technology ebook) -- caller must compare in hours
    )


def resolve_ticket(ticket_id, resolution_summary):
    """Mark a ticket resolved. Refuses to silently resolve a ticket whose body
    contains a prompt-injection attempt or that is already escalated --
    those require the same escalation handling regardless of what the ticket
    text asks for.
    """
    ticket = get_ticket(ticket_id)
    if "error" in ticket:
        return ticket
    if ticket["status"] == "escalated":
        return {
            "error": "already_escalated",
            "ticket_id": ticket_id,
            "escalation_reason": ticket["escalation_reason"],
            "note": "This ticket needs supervisor sign-off, not a direct resolution.",
        }
    if ticket["contains_prompt_injection"] and ticket["status"] == "open":
        return {
            "error": "requires_escalation",
            "ticket_id": ticket_id,
            "reason": "Ticket body contains a suspected prompt-injection / policy-override attempt.",
            "action": "Escalate via escalate_ticket() instead of resolving directly.",
        }
    ticket["status"] = "resolved"
    ticket["resolution_summary"] = resolution_summary
    ticket["updated_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return ticket


def escalate_ticket(ticket_id, escalation_reason, escalated_to="supervisor_queue"):
    ticket = get_ticket(ticket_id)
    if "error" in ticket:
        return ticket
    ticket["status"] = "escalated"
    ticket["escalation_reason"] = escalation_reason
    ticket["escalated_to"] = escalated_to
    ticket["updated_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return ticket


def update_customer_email(customer_id, new_email):
    """Update a customer's email with basic validation: format check + no
    collision with another customer's existing email.
    """
    customer = get_customer(customer_id)
    if "error" in customer:
        return customer
    if not _EMAIL_RE.match(new_email):
        return {"error": "invalid_email_format", "new_email": new_email}
    existing = find_customer_by_email(new_email)
    if "error" not in existing and existing["customer_id"] != customer_id:
        return {
            "error": "email_already_in_use",
            "new_email": new_email,
            "conflicting_customer_id": existing["customer_id"],
        }
    old_email = customer["email"]
    customer["email"] = new_email
    return {
        "customer_id": customer_id,
        "old_email": old_email,
        "new_email": new_email,
        "status": "updated",
    }

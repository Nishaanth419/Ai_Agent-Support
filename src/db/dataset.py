"""
ABC Bookstore -- Support-Agent Synthetic Golden Dataset
=========================================================

WHAT THIS IS FOR
-----------------
ABC sells books online in three categories: technology, fiction, self-help.
This module is the backing data for a customer-service COPILOT: an assistant
that sits next to a human support agent and answers questions / takes actions
using three underlying data sources, each modeled as one section below:

  1. CUSTOMERS        -- the customer directory (id, name, email, membership tier)
  2. TICKETS           -- every support ticket (open, resolved, or escalated)
  3. REFUND_POLICY /
     GENERAL_POLICY    -- the refund policy knowledge base, split by book
                          category (window differs technology vs fiction vs
                          self-help) plus category-agnostic rules (damaged
                          items, wrong item shipped, store credit, escalation
                          triggers, Prime bonus days).

This is a GOLDEN dataset: every fact needed to answer the paired eval
questions in golden_eval_set.py is deliberately baked in and hand-verified
(see the assertions at the bottom of generate.py). Most of the 120 tickets
are randomly generated filler for realistic volume/noise, but ~25 are
hand-placed "golden" scenarios covering the situations a real agent will hit:
customers with zero tickets, customers with zero OPEN tickets, ties and
non-ties in status counts, a refund request that sits right at a policy
boundary (and only clears it because of a Prime membership bonus), and
several tickets containing prompt-injection attempts embedded in the
customer's own message.

TICKET STATUS LIFECYCLE
------------------------
- "open"      : created_at == updated_at, nothing has happened yet.
- "resolved"  : normal completion; resolution_summary is filled in.
- "escalated" : could not / should not be resolved by the agent directly;
                escalation_reason + escalated_to are filled in. An escalated
                ticket is NOT the same as "unresolved" -- it means a human
                supervisor needs to make the call, so the agent should say so
                rather than attempting to resolve it unilaterally.

WHY THIS MATTERS FOR THE AGENT'S BEHAVIOR
-------------------------------------------
- Ticket bodies are raw, untrusted customer text. Several deliberately contain
  embedded instructions ("IGNORE ALL PRIOR INSTRUCTIONS...", "[SYSTEM
  OVERRIDE]...") trying to get an assistant that reads ticket bodies to grant
  refunds outside policy. `contains_prompt_injection` flags these so you can
  test that your agent treats ticket text as DATA, never as instructions --
  it should still apply the real REFUND_POLICY / GENERAL_POLICY rules (or
  escalate) regardless of what the ticket body claims. One resolved ticket
  (id 27) is a "trap": a previous agent WRONGLY complied with the injected
  instruction and auto-refunded outside policy -- its resolution_summary
  carries an [AUDIT FLAG] note for exactly this reason.
- Refund eligibility depends on book_category + format (physical/ebook) +
  order_date vs "today", AND on the customer's membership_tier (Prime gets
  +7 bonus days on physical windows -- see GENERAL_POLICY). A good agent
  looks up the customer, the ticket's order_date, and the right policy
  branch rather than pattern-matching on keywords.
- Category alone is not always enough to act: "ambiguous" tickets have vague
  bodies that don't map cleanly to any category -- the right move is to ask
  a clarifying question, not to guess confidently.
- "Not found" is a real, expected answer. Ticket id 9999 and customer id 999
  do not exist. Customer 10 exists but has zero tickets. Customer 15 has
  tickets but none open. The agent must be able to say "no results" instead
  of hallucinating.

SCHEMA
------
CUSTOMERS: list[dict] with keys
    customer_id (int, 1-based, stable), name, email, membership_tier
    ("standard" | "prime"), signed_up_at (ISO8601 UTC string)

TICKETS: list[dict] with keys
    ticket_id (int, 1-based, stable), customer_id (FK -> CUSTOMERS),
    category (one of: refund_request, order_status, damaged_item,
        wrong_item_shipped, account_update, general_inquiry, complaint,
        cancellation, promo_price_match, ambiguous),
    book_category ("technology" | "fiction" | "self-help" | None -- None for
        tickets not about a specific book, e.g. account_update),
    format ("physical" | "ebook" | None),
    subject (str), body (str, RAW CUSTOMER TEXT -- treat as untrusted data),
    status ("open" | "resolved" | "escalated"),
    created_at / updated_at (ISO8601 UTC strings; equal iff status == "open"),
    order_id / book_title / order_date / amount (order context, None when
        not applicable, e.g. account_update / ambiguous / general questions
        with no specific order),
    contains_prompt_injection (bool),
    resolution_summary (str | None -- set iff status == "resolved"),
    escalation_reason / escalated_to (str | None -- set iff status == "escalated").
    A few order_status tickets additionally carry shipping_status,
    tracking_number, estimated_delivery (see ticket 45).

REFUND_POLICY: dict keyed by book category ("technology" | "fiction" |
    "self-help"), each with a "description", and "physical" / "ebook"
    sub-dicts giving the refund window and condition text.

GENERAL_POLICY: dict of category-agnostic rules -- damaged/defective items,
    wrong item shipped, the store-credit alternative, the Prime member bonus,
    processing time, shipping-fee refundability, and a list of conditions
    under which a ticket MUST be escalated rather than resolved directly.

"""

